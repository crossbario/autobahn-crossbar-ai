"""Compare upstream py-lmdb with the aspect's pinned baseline, or regenerate it.

Not part of the check: ``check.py`` and ``reconcile.py`` stay offline and read only
the pinned baseline. This script is how a person (or an agent) learns that upstream
moved, and how the baseline is bumped - a change to this aspect, followed by a
rollout (see ``../SKILL.md``).

It needs local git checkouts of upstream (fetch them first; it never fetches):

- py-lmdb (https://github.com/jnwatson/py-lmdb): the release tag, its patch series
  (``lib/py-lmdb/``, ``lib1/py-lmdb/``), its tests, and which LMDB version each
  bundled tree is (``lib*/lmdb.h``);
- LMDB (https://github.com/LMDB/lmdb): the commit each ``LMDB_x.y.z`` tag names.

Usage::

    python upstream_watch.py --py-lmdb <dir> --lmdb <dir> [--tag py-lmdb_X.Y.Z]
    python upstream_watch.py --py-lmdb <dir> --lmdb <dir> --write

Without ``--tag``, the newest ``py-lmdb_*`` release tag is used. Exit code: 0 if the
baseline matches that upstream release (or was written), 1 if it differs.
"""

from __future__ import annotations

import argparse
import hashlib
import re
import subprocess
import sys
import tomllib
from pathlib import Path

from _fork import BASELINE

ENGINES = ("lib", "lib1")
_RELEASE = re.compile(r"py-lmdb_(\d+)\.(\d+)\.(\d+)")
_LMDB_VERSION = re.compile(r"(?m)^#define MDB_VERSION_(MAJOR|MINOR|PATCH)\s+(\d+)")
_TEST_CASE = re.compile(r"(?m)^\s*def (test_\w+)\s*\(")


def _git(repo: Path, *args: str) -> str:
    return subprocess.run(  # noqa: S603 - fixed program, git arguments
        ["git", "-C", str(repo), *args],  # noqa: S607
        capture_output=True,
        text=True,
        check=True,
    ).stdout


def _git_bytes(repo: Path, *args: str) -> bytes:
    return subprocess.run(  # noqa: S603 - fixed program, git arguments
        ["git", "-C", str(repo), *args],  # noqa: S607
        capture_output=True,
        check=True,
    ).stdout


def newest_release(py_lmdb: Path) -> str:
    """The newest ``py-lmdb_X.Y.Z`` tag, by version (not by date)."""
    tags = [t for t in _git(py_lmdb, "tag", "--list", "py-lmdb_*").split() if t]
    releases = [
        (tuple(map(int, m.groups())), t) for t in tags if (m := _RELEASE.fullmatch(t))
    ]
    if not releases:
        msg = f"{py_lmdb}: no py-lmdb_X.Y.Z tag"
        raise SystemExit(msg)
    return max(releases)[1]


def _files(py_lmdb: Path, tag: str, folder: str) -> list[str]:
    out = _git(py_lmdb, "ls-tree", "--name-only", f"{tag}:{folder}")
    return sorted(name for name in out.splitlines() if name)


def _lmdb_tag(py_lmdb: Path, tag: str, tree: str) -> str:
    header = _git(py_lmdb, "show", f"{tag}:{tree}/lmdb.h")
    parts = dict(_LMDB_VERSION.findall(header))
    return f"LMDB_{parts['MAJOR']}.{parts['MINOR']}.{parts['PATCH']}"


def upstream_baseline(py_lmdb: Path, lmdb: Path, tag: str) -> dict:
    """The baseline that upstream release ``tag`` implies (same shape as the file)."""
    base: dict = {
        "py-lmdb": {
            "version": tag.removeprefix("py-lmdb_"),
            "tag": tag,
            "commit": _git(py_lmdb, "rev-parse", f"{tag}^{{commit}}").strip(),
        },
        "lmdb": {},
        "patches": {},
        "tests": {},
    }
    for tree in ENGINES:
        lmdb_tag = _lmdb_tag(py_lmdb, tag, tree)
        base["lmdb"][tree] = {
            "tag": lmdb_tag,
            "commit": _git(lmdb, "rev-parse", f"{lmdb_tag}^{{commit}}").strip(),
        }
        folder = f"{tree}/py-lmdb"
        base["patches"][tree] = {
            name: hashlib.sha256(
                _git_bytes(py_lmdb, "show", f"{tag}:{folder}/{name}")
            ).hexdigest()
            for name in _files(py_lmdb, tag, folder)
        }
    for name in _files(py_lmdb, tag, "tests"):
        if name.endswith("_test.py"):
            text = _git(py_lmdb, "show", f"{tag}:tests/{name}")
            base["tests"][name] = {"cases": sorted(set(_TEST_CASE.findall(text)))}
    return base


def render(base: dict) -> str:
    """The baseline as TOML, canonically ordered (stable diffs, stable digests)."""
    py = base["py-lmdb"]
    lines = [
        "# Pinned upstream baseline for the zlmdb-py-lmdb-fork aspect.",
        "# GENERATED by scripts/upstream_watch.py --write - do not edit by hand.",
        "",
        "schema = 1",
        "",
        "[py-lmdb]",
        f'version = "{py["version"]}"',
        f'tag     = "{py["tag"]}"',
        f'commit  = "{py["commit"]}"',
    ]
    for tree in ENGINES:
        lmdb = base["lmdb"][tree]
        lines += [
            "",
            f"[lmdb.{tree}]",
            f'tag    = "{lmdb["tag"]}"',
            f'commit = "{lmdb["commit"]}"',
        ]
    for tree in ENGINES:
        lines += ["", f"[patches.{tree}]  # {tree}/py-lmdb/: file name -> sha256"]
        lines += [f'"{n}" = "{h}"' for n, h in sorted(base["patches"][tree].items())]
    for name, test in sorted(base["tests"].items()):
        lines += ["", f'[tests."{name}"]', "cases = ["]
        lines += [f'    "{case}",' for case in test["cases"]]
        lines.append("]")
    return "\n".join(lines) + "\n"


def compare(pinned: dict, upstream: dict) -> list[str]:
    """Human-readable differences between the pinned and the upstream baseline."""
    diffs = []
    if pinned["py-lmdb"]["version"] != upstream["py-lmdb"]["version"]:
        diffs.append(
            f"py-lmdb {pinned['py-lmdb']['version']} -> "
            f"{upstream['py-lmdb']['version']}"
        )
    for tree in ENGINES:
        old, new = pinned["lmdb"][tree]["tag"], upstream["lmdb"][tree]["tag"]
        if old != new:
            diffs.append(f"LMDB ({tree}) {old} -> {new}")
        old_p, new_p = pinned["patches"][tree], upstream["patches"][tree]
        for name in sorted(set(old_p) | set(new_p)):
            if old_p.get(name) != new_p.get(name):
                change = (
                    "added"
                    if name not in old_p
                    else "removed"
                    if name not in new_p
                    else "changed"
                )
                diffs.append(f"{tree}/py-lmdb/{name}: {change}")
    old_t, new_t = pinned["tests"], upstream["tests"]
    for name in sorted(set(old_t) | set(new_t)):
        old_c = set(old_t.get(name, {}).get("cases", []))
        new_c = set(new_t.get(name, {}).get("cases", []))
        if added := sorted(new_c - old_c):
            diffs.append(f"tests/{name}: {len(added)} new case(s)")
        if removed := sorted(old_c - new_c):
            diffs.append(f"tests/{name}: {len(removed)} removed case(s)")
    return diffs


def main(argv: list[str] | None = None) -> int:
    """Report how upstream differs from the pinned baseline, or write a new one."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--py-lmdb", type=Path, required=True, help="py-lmdb checkout")
    parser.add_argument("--lmdb", type=Path, required=True, help="LMDB checkout")
    parser.add_argument("--tag", help="py-lmdb release tag (default: the newest)")
    parser.add_argument(
        "--write", action="store_true", help=f"write {BASELINE.name} from upstream"
    )
    args = parser.parse_args(argv)

    tag = args.tag or newest_release(args.py_lmdb)
    upstream = upstream_baseline(args.py_lmdb, args.lmdb, tag)
    if args.write:
        BASELINE.write_text(render(upstream), encoding="utf-8")
        print(f"wrote {BASELINE} for {tag}")
        return 0
    pinned = tomllib.loads(BASELINE.read_text(encoding="utf-8"))
    diffs = compare(pinned, upstream)
    if not diffs:
        print(f"baseline matches {tag}")
        return 0
    print(f"baseline differs from {tag}:")
    for line in diffs:
        print(f"  {line}")
    return 1


if __name__ == "__main__":
    sys.exit(main())
